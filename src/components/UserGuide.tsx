export function UserGuide() {
  /** 同一时间只展开一条：十二条全摊开就又变成一篇要滚半天的长文了 */
  const [openIndex, setOpenIndex] = useState<number | null>(null)

  return (
    <div className="space-y-1.5">
      <p className="text-xs text-ink-muted leading-relaxed px-0.5 pb-1">
        下面这些是界面上不太容易看出来的。点一条展开。
      </p>
      {TOPICS.map((t, i) => {
        const on = openIndex === i
        return (
          <div
            key={t.q}
            className="rounded-xl border border-paper-border bg-stone-50/60 overflow-hidden"
          >
            <button
              type="button"
              onClick={() => setOpenIndex(on ? null : i)}
              className="w-full flex items-center gap-2 px-3 py-2.5 text-left"
              aria-expanded={on}
            >
              <span className="flex-1 text-sm text-ink">{t.q}</span>
              <ChevronDown
                className={`w-4 h-4 shrink-0 text-ink-muted transition-transform ${
                  on ? 'rotate-180' : ''
                }`}
                aria-hidden
              />
            </button>
            {on && (
              <div className="px-3 pb-3 -mt-0.5 text-xs text-ink-muted leading-relaxed">
                {t.a}
              </div>
            )}
          </div>
        )
      })}
    </div>
  )
}
