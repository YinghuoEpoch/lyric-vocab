/**
 * 三列（左侧栏 / 主区 / 右侧栏）顶部共用的两条带。
 *
 * 起因：用户说「三个部分的顶部各有不同，看起来不协调」。量出来是**五条横线落在
 * 五个不同高度**上 —— 主区顶栏底边 37、左侧栏顶栏 55、主区第二条 74、
 * 右侧栏顶栏 99、左侧栏「阅读/复习」底边 116。眼睛横着扫过去，五条线全对不上。
 *
 * 另外两处小的：分隔线是两种灰（侧栏 paper-border 暖灰 rgb(229,227,223)、
 * 主区 gray-200 冷灰 rgb(229,231,235)），左右内边距 12/12/16/12 也不齐。
 *
 * 但结构上本来就有救 —— 三列的顶部其实都在做同两件事，只是没对齐：
 *
 * |      | 第一带：这是什么        | 第二带：模式 / 动作          |
 * |------|------------------------|-----------------------------|
 * | 左   | 我的文库 + 整理         | 阅读 ｜ 复习                 |
 * | 中   | 文档标题 + 两个抽屉键   | 长按提示 + 编辑全文 / 复习工具 |
 * | 右   | 笔记(n) + AI 划词       | 生词 ｜ 句摘                 |
 *
 * 所以把两带的高度、内边距、分隔线统一，横着看就只剩两条通栏的线。
 *
 * 用 `min-h-` 不用 `h-`：内容装得下时高度就是这个数、三列对得齐；
 * 万一哪天塞多了要折行（复习页那条是 flex-wrap 的），它能自己长高而不是把内容切掉。
 */

